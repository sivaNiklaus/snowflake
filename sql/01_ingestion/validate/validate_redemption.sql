SELECT COUNT(*) AS REDEMPTION_RAW_ROW_COUNT
FROM SKYPOINTS_DB.RAW.REDEMPTION_RAW;

SELECT
    PAYLOAD,
    SOURCE_FILENAME,
    SOURCE_ROW_NUMBER,
    SOURCE_FILE_CONTENT_KEY,
    INGESTED_AT
FROM SKYPOINTS_DB.RAW.REDEMPTION_RAW
ORDER BY INGESTED_AT DESC, SOURCE_ROW_NUMBER
LIMIT 20;

SELECT
    COUNT_IF(PAYLOAD IS NULL) AS NULL_PAYLOADS,
    COUNT_IF(SOURCE_FILENAME IS NULL) AS NULL_SOURCE_FILENAMES,
    COUNT_IF(SOURCE_ROW_NUMBER IS NULL) AS NULL_SOURCE_ROW_NUMBERS,
    COUNT_IF(SOURCE_FILE_CONTENT_KEY IS NULL) AS NULL_SOURCE_CONTENT_KEYS,
    COUNT_IF(INGESTED_AT IS NULL) AS NULL_INGESTED_AT_VALUES
FROM SKYPOINTS_DB.RAW.REDEMPTION_RAW;

SELECT
    COUNT_IF(SOURCE_FILENAME IS NULL OR INGESTED_AT IS NULL)
        AS ROWS_MISSING_FILENAME_OR_INGESTED_AT,
    MIN(INGESTED_AT) AS FIRST_INGESTED_AT,
    MAX(INGESTED_AT) AS LAST_INGESTED_AT
FROM SKYPOINTS_DB.RAW.REDEMPTION_RAW;

SELECT
    FILE_NAME,
    LAST_LOAD_TIME,
    STATUS,
    ROW_COUNT,
    ERROR_COUNT,
    FIRST_ERROR_MESSAGE
FROM TABLE(SKYPOINTS_DB.INFORMATION_SCHEMA.COPY_HISTORY(
    TABLE_NAME => 'SKYPOINTS_DB.RAW.REDEMPTION_RAW',
    START_TIME => DATEADD('DAY', -14, CURRENT_TIMESTAMP())
))
ORDER BY LAST_LOAD_TIME DESC;
