-- Unified Phase 3-6C orchestration history and live operational metrics.

-- Run outcome, graph identity, overlap guard, and comparison with previous runs.
SELECT
    run.RUN_ID,
    run.GRAPH_RUN_ID,
    run.STATUS,
    run.STARTED_AT,
    run.ENDED_AT,
    DATEDIFF('SECOND', run.STARTED_AT, COALESCE(run.ENDED_AT, CURRENT_TIMESTAMP()))
        AS DURATION_SECONDS,
    run.TASK_COUNT,
    run.FAILED_TASKS,
    run.ERROR_DETAILS,
    run.CLEANUP_ERRORS,
    LAG(run.STATUS) OVER (ORDER BY run.STARTED_AT) AS PREVIOUS_RUN_STATUS,
    LAG(run.TASK_COUNT) OVER (ORDER BY run.STARTED_AT) AS PREVIOUS_RUN_TASK_COUNT
FROM SKYPOINTS_DB.AUDIT.PIPELINE_RUN_AUDIT AS run
ORDER BY run.STARTED_AT DESC
LIMIT 100;

SELECT CONTROL_NAME, STATUS, ACTIVE_RUN_ID, UPDATED_AT
FROM SKYPOINTS_DB.AUDIT.PIPELINE_RUN_CONTROL;

-- Per-task state and elapsed time, correlated to the controlled graph audit.
SELECT
    run.RUN_ID AS PIPELINE_RUN_ID,
    history.GRAPH_RUN_GROUP_ID AS GRAPH_RUN_ID,
    history.NAME AS TASK_NAME,
    history.STATE,
    COALESCE(history.QUERY_START_TIME, history.SCHEDULED_TIME) AS STARTED_AT,
    history.COMPLETED_TIME AS ENDED_AT,
    DATEDIFF(
        'SECOND',
        COALESCE(history.QUERY_START_TIME, history.SCHEDULED_TIME),
        history.COMPLETED_TIME
    ) AS DURATION_SECONDS,
    history.ERROR_MESSAGE
FROM TABLE(SKYPOINTS_DB.INFORMATION_SCHEMA.TASK_HISTORY(
    SCHEDULED_TIME_RANGE_START => DATEADD('DAY', -30, CURRENT_TIMESTAMP()),
    SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP(),
    DATABASE_NAME => 'SKYPOINTS_DB',
    SCHEMA_NAME => 'RAW',
    RESULT_LIMIT => 1000
)) AS history
LEFT JOIN SKYPOINTS_DB.AUDIT.PIPELINE_RUN_AUDIT AS run
  ON run.GRAPH_RUN_ID = history.GRAPH_RUN_GROUP_ID
WHERE history.NAME IN
(
    'TASK_MEMBER_INGESTION',
    'TASK_REDEMPTION_INGESTION',
    'TASK_INGESTION_VALIDATION',
    'TASK_PARSE_AND_NORMALIZE',
    'TASK_DQ_VALIDATION',
    'TASK_MEMBER_PROCESSING',
    'TASK_REDEMPTION_PROCESSING',
    'TASK_COUNTRY_ROUTING',
    'TASK_COUNTRY_RECONCILIATION'
)
ORDER BY history.SCHEDULED_TIME DESC;

-- Per-file incremental checkpoints; STARTED/FAILED rows are eligible for retry.
SELECT
    RUN_ID AS GRAPH_RUN_ID,
    DATASET_NAME,
    STAGE_NAME,
    STATUS,
    COUNT(*) AS FILE_COUNT,
    SUM(ROWS_PROCESSED) AS ROWS_PROCESSED,
    MIN(STARTED_AT) AS FIRST_STARTED_AT,
    MAX(ENDED_AT) AS LAST_ENDED_AT,
    LISTAGG(
        IFF(STATUS = 'FAILED',
            SOURCE_FILENAME || ': ' || ERROR_DETAILS,
            NULL),
        '; '
    ) WITHIN GROUP (ORDER BY SOURCE_FILENAME) AS FAILURE_DETAILS
FROM SKYPOINTS_DB.AUDIT.ETL_FILE_STAGE_STATUS
GROUP BY RUN_ID, DATASET_NAME, STAGE_NAME, STATUS
ORDER BY MAX(STARTED_AT) DESC, DATASET_NAME, STAGE_NAME;

-- Raw load counts and file names returned by Snowflake COPY INTO.
SELECT
    audit.RUN_ID AS GRAPH_RUN_ID,
    audit.TASK_NAME,
    audit.STATUS,
    audit.ROWS_LOADED,
    audit.SOURCE_FILES,
    audit.ERROR_DETAILS
FROM SKYPOINTS_DB.AUDIT.INGESTION_AUDIT AS audit
ORDER BY audit.STARTED_AT DESC
LIMIT 300;

-- Per-run DQ totals; failed rule results are distinct-counted per record.
-- The separate live snapshot below retains lifetime quarantine visibility.
SELECT
    dq.RUN_ID AS GRAPH_RUN_ID,
    dq.DATASET_NAME,
    dq.STATUS,
    dq.TOTAL_RECORDS,
    dq.VALID_RECORDS,
    dq.INVALID_RECORDS,
    dq.DUPLICATE_COUNT,
    COALESCE(failed_records.QUARANTINED_COUNT, 0) AS QUARANTINED_COUNT,
    dq.ERROR_DETAILS
FROM SKYPOINTS_DB.AUDIT.DQ_EXECUTION AS dq
LEFT JOIN
(
    SELECT RUN_ID, DATASET_NAME,
           COUNT(DISTINCT RECORD_KEY) AS QUARANTINED_COUNT
    FROM SKYPOINTS_DB.AUDIT.DQ_RULE_RESULT
    WHERE DATASET_NAME IN ('MEMBER', 'REDEMPTION')
      AND STATUS = 'FAILED'
    GROUP BY RUN_ID, DATASET_NAME
) AS failed_records
  ON failed_records.RUN_ID = dq.RUN_ID
 AND failed_records.DATASET_NAME = dq.DATASET_NAME
ORDER BY dq.STARTED_AT DESC, dq.DATASET_NAME
LIMIT 300;

-- Current business-table totals are live snapshots, not per-run deltas.
SELECT
    CURRENT_TIMESTAMP() AS SNAPSHOT_AT,
    (SELECT COUNT(*) FROM SKYPOINTS_DB.RAW.MEMBER_PROFILE_RAW)
        AS MEMBER_RAW_ROWS,
    (SELECT COUNT(*) FROM SKYPOINTS_DB.RAW.REDEMPTION_RAW)
        AS REDEMPTION_RAW_ROWS,
    (SELECT COUNT(*) FROM SKYPOINTS_DB.CORE.MEMBER_CURRENT)
        AS CURRENT_MEMBERS,
    (SELECT COUNT(*) FROM SKYPOINTS_DB.CORE.MEMBER_HISTORY)
        AS MEMBER_HISTORY_ROWS,
    (SELECT COUNT(*) FROM SKYPOINTS_DB.CORE.REDEMPTION_FACT)
        AS REDEMPTION_FACT_ROWS,
    (SELECT COUNT(*) FROM SKYPOINTS_DB.STAGING.DQ_QUARANTINE)
        AS ALL_QUARANTINED_RECORDS;

-- Country operation counts and reconciliation status for each completed graph.
SELECT
    routing.RUN_ID AS GRAPH_RUN_ID,
    routing.STATUS AS ROUTING_STATUS,
    routing.TOTAL_MEMBERS,
    routing.ROUTED_MEMBERS,
    routing.INSERTED_COUNT,
    routing.UPDATED_COUNT,
    routing.REMOVED_COUNT,
    routing.QUARANTINED_COUNT,
    reconciliation.CHECK_COUNT,
    reconciliation.FAILED_CHECK_COUNT,
    IFF(
        reconciliation.RUN_ID IS NULL,
        'NOT_RECORDED',
        IFF(
            reconciliation.EXECUTION_FAILED_COUNT > 0
                OR reconciliation.FAILED_CHECK_COUNT > 0,
            'FAILED',
            IFF(reconciliation.CHECK_COUNT = 0, 'NOT_RECORDED', 'PASSED')
        )
    ) AS RECONCILIATION_STATUS,
    routing.ERROR_DETAILS
FROM SKYPOINTS_DB.AUDIT.COUNTRY_ROUTING_AUDIT AS routing
LEFT JOIN
(
    SELECT
        RUN_ID,
        COALESCE(
            COUNT_IF(CHECK_NAME <> 'RECONCILIATION_EXECUTION'),
            0
        ) AS CHECK_COUNT,
        COALESCE(
            COUNT_IF(
                CHECK_NAME <> 'RECONCILIATION_EXECUTION'
                AND STATUS = 'FAILED'
            ),
            0
        ) AS FAILED_CHECK_COUNT,
        COALESCE(
            COUNT_IF(
                CHECK_NAME = 'RECONCILIATION_EXECUTION'
                AND STATUS = 'FAILED'
            ),
            0
        ) AS EXECUTION_FAILED_COUNT
    FROM SKYPOINTS_DB.AUDIT.COUNTRY_RECONCILIATION_AUDIT
    GROUP BY RUN_ID
) AS reconciliation
  ON reconciliation.RUN_ID = routing.RUN_ID
ORDER BY routing.STARTED_AT DESC
LIMIT 100;

-- Failure drill-down combines task history with stage/procedure audit details.
WITH task_history AS
(
    SELECT *
    FROM TABLE(SKYPOINTS_DB.INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START => DATEADD('DAY', -30, CURRENT_TIMESTAMP()),
        SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP(),
        DATABASE_NAME => 'SKYPOINTS_DB',
        SCHEMA_NAME => 'RAW',
        RESULT_LIMIT => 1000
    ))
)
SELECT
    run.RUN_ID,
    run.GRAPH_RUN_ID,
    run.STATUS AS PIPELINE_STATUS,
    history.NAME AS FAILED_TASK_NAME,
    history.STATE AS TASK_STATE,
    history.ERROR_MESSAGE AS TASK_ERROR,
    ingestion.ERROR_DETAILS AS INGESTION_ERROR,
    processing.ERROR_DETAILS AS PROCESSING_ERROR
FROM SKYPOINTS_DB.AUDIT.PIPELINE_RUN_AUDIT AS run
LEFT JOIN task_history AS history
  ON history.GRAPH_RUN_GROUP_ID = run.GRAPH_RUN_ID
 AND history.STATE IN ('FAILED', 'CANCELLED', 'SKIPPED')
LEFT JOIN SKYPOINTS_DB.AUDIT.INGESTION_AUDIT AS ingestion
  ON ingestion.RUN_ID = run.GRAPH_RUN_ID
 AND ingestion.STATUS = 'FAILED'
LEFT JOIN SKYPOINTS_DB.AUDIT.PHASE45_AUDIT AS processing
  ON processing.RUN_ID = run.GRAPH_RUN_ID
 AND processing.STATUS = 'FAILED'
WHERE run.STATUS <> 'SUCCEEDED'
ORDER BY run.STARTED_AT DESC;
