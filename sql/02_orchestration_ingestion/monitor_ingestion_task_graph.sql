WITH task_history AS
(
    SELECT
        NAME,
        STATE,
        GRAPH_RUN_GROUP_ID,
        SCHEDULED_TIME,
        QUERY_START_TIME,
        COMPLETED_TIME,
        ERROR_MESSAGE
    FROM TABLE(SKYPOINTS_DB.INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START => DATEADD('DAY', -7, CURRENT_TIMESTAMP()),
        SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP(),
        TASK_NAME => 'TASK_MEMBER_INGESTION',
        DATABASE_NAME => 'SKYPOINTS_DB',
        SCHEMA_NAME => 'RAW',
        RESULT_LIMIT => 100
    ))

    UNION ALL

    SELECT
        NAME,
        STATE,
        GRAPH_RUN_GROUP_ID,
        SCHEDULED_TIME,
        QUERY_START_TIME,
        COMPLETED_TIME,
        ERROR_MESSAGE
    FROM TABLE(SKYPOINTS_DB.INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START => DATEADD('DAY', -7, CURRENT_TIMESTAMP()),
        SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP(),
        TASK_NAME => 'TASK_REDEMPTION_INGESTION',
        DATABASE_NAME => 'SKYPOINTS_DB',
        SCHEMA_NAME => 'RAW',
        RESULT_LIMIT => 100
    ))

    UNION ALL

    SELECT
        NAME,
        STATE,
        GRAPH_RUN_GROUP_ID,
        SCHEDULED_TIME,
        QUERY_START_TIME,
        COMPLETED_TIME,
        ERROR_MESSAGE
    FROM TABLE(SKYPOINTS_DB.INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START => DATEADD('DAY', -7, CURRENT_TIMESTAMP()),
        SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP(),
        TASK_NAME => 'TASK_INGESTION_VALIDATION',
        DATABASE_NAME => 'SKYPOINTS_DB',
        SCHEMA_NAME => 'RAW',
        RESULT_LIMIT => 100
    ))
)
SELECT
    NAME,
    STATE,
    GRAPH_RUN_GROUP_ID,
    SCHEDULED_TIME,
    QUERY_START_TIME,
    COMPLETED_TIME,
    ERROR_MESSAGE
FROM task_history
ORDER BY SCHEDULED_TIME DESC;

SELECT
    RUN_ID,
    TASK_NAME,
    STARTED_AT,
    ENDED_AT,
    STATUS,
    ROWS_LOADED,
    MEMBER_ROW_COUNT,
    REDEMPTION_ROW_COUNT,
    SOURCE_FILES,
    ERROR_DETAILS
FROM SKYPOINTS_DB.AUDIT.INGESTION_AUDIT
ORDER BY STARTED_AT DESC
LIMIT 100;
