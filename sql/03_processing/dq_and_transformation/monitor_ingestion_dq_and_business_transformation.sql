-- Recent task execution history for the complete Phase 3-5 graph.
SELECT
    NAME,
    STATE,
    GRAPH_RUN_GROUP_ID,
    SCHEDULED_TIME,
    QUERY_START_TIME,
    COMPLETED_TIME,
    ERROR_MESSAGE
FROM TABLE(SKYPOINTS_DB.INFORMATION_SCHEMA.TASK_HISTORY(
    SCHEDULED_TIME_RANGE_START => DATEADD('DAY', -7, CURRENT_TIMESTAMP()),
    SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP(),
    DATABASE_NAME => 'SKYPOINTS_DB',
    SCHEMA_NAME => 'RAW',
    RESULT_LIMIT => 1000
))
WHERE NAME IN
(
    'TASK_MEMBER_INGESTION',
    'TASK_REDEMPTION_INGESTION',
    'TASK_INGESTION_VALIDATION',
    'TASK_PARSE_AND_NORMALIZE',
    'TASK_DQ_VALIDATION',
    'TASK_MEMBER_PROCESSING',
    'TASK_REDEMPTION_PROCESSING'
)
ORDER BY SCHEDULED_TIME DESC;

-- Phase 3 ingestion audit rows for the same graph.
SELECT
    RUN_ID,
    TASK_NAME,
    STARTED_AT,
    ENDED_AT,
    STATUS,
    ROWS_LOADED,
    MEMBER_ROW_COUNT,
    REDEMPTION_ROW_COUNT,
    SOURCE_FILES,
    ERROR_DETAILS
FROM SKYPOINTS_DB.AUDIT.INGESTION_AUDIT
ORDER BY STARTED_AT DESC
LIMIT 100;

-- Per-procedure start/end status and technical error messages.
SELECT
    RUN_ID,
    TASK_NAME,
    STARTED_AT,
    ENDED_AT,
    STATUS,
    ROWS_PROCESSED,
    ERROR_DETAILS
FROM SKYPOINTS_DB.AUDIT.PHASE45_AUDIT
ORDER BY STARTED_AT DESC
LIMIT 100;

-- Per-dataset DQ counts; invalid rows are expected to be quarantined, not fatal.
SELECT
    RUN_ID,
    DATASET_NAME,
    STARTED_AT,
    ENDED_AT,
    STATUS,
    TOTAL_RECORDS,
    VALID_RECORDS,
    INVALID_RECORDS,
    DUPLICATE_COUNT,
    ERROR_DETAILS
FROM SKYPOINTS_DB.AUDIT.DQ_EXECUTION
ORDER BY STARTED_AT DESC, DATASET_NAME
LIMIT 100;

-- Rule-level outcomes for the most recent graph run(s).
SELECT
    RUN_ID,
    DATASET_NAME,
    RULE_ID,
    STATUS,
    SUM(EVALUATED_COUNT) AS EVALUATED_COUNT,
    SUM(FAILURE_COUNT) AS FAILURE_COUNT
FROM SKYPOINTS_DB.AUDIT.DQ_RULE_RESULT
GROUP BY RUN_ID, DATASET_NAME, RULE_ID, STATUS
ORDER BY RUN_ID DESC, DATASET_NAME, RULE_ID, STATUS;

-- Quarantine count and retained source lineage.
SELECT
    DATASET_NAME,
    COUNT(*) AS QUARANTINED_RECORDS,
    MIN(QUARANTINED_AT) AS FIRST_QUARANTINED_AT,
    MAX(QUARANTINED_AT) AS LAST_QUARANTINED_AT
FROM SKYPOINTS_DB.STAGING.DQ_QUARANTINE
GROUP BY DATASET_NAME
ORDER BY DATASET_NAME;

-- Current/history consistency and redemption referential-integrity checks.
SELECT
    (SELECT COUNT(*) FROM SKYPOINTS_DB.CORE.MEMBER_CURRENT) AS CURRENT_MEMBERS,
    (SELECT COUNT_IF(IS_CURRENT) FROM SKYPOINTS_DB.CORE.MEMBER_HISTORY)
        AS CURRENT_HISTORY_ROWS,
    (SELECT COUNT(*) FROM SKYPOINTS_DB.CORE.REDEMPTION_FACT) AS REDEMPTION_FACTS,
    (SELECT COUNT_IF(member.MEMBER_ID IS NULL)
       FROM SKYPOINTS_DB.CORE.REDEMPTION_FACT AS redemption
       LEFT JOIN SKYPOINTS_DB.CORE.MEMBER_CURRENT AS member
         ON member.MEMBER_ID = redemption.MEMBER_ID)
        AS REDEMPTIONS_WITHOUT_CURRENT_MEMBER;
