DEFINE FILE FORMAT SKYPOINTS_DB.RAW.MEMBER_PROFILE_CSV
    TYPE = CSV
    FIELD_DELIMITER = '|'
    SKIP_HEADER = 0
    PARSE_HEADER = FALSE
    EMPTY_FIELD_AS_NULL = FALSE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    COMMENT = 'Raw pipe-delimited member feed; preserve all source positions';

DEFINE FILE FORMAT SKYPOINTS_DB.RAW.REDEMPTION_JSON
    TYPE = JSON
    STRIP_OUTER_ARRAY = FALSE
    STRIP_NULL_VALUES = FALSE
    COMMENT = 'Raw partner redemption JSON documents';

DEFINE TABLE SKYPOINTS_DB.RAW.MEMBER_PROFILE_RAW
(
    SOURCE_COLUMN_01 VARCHAR,
    SOURCE_COLUMN_02 VARCHAR,
    SOURCE_COLUMN_03 VARCHAR,
    SOURCE_COLUMN_04 VARCHAR,
    SOURCE_COLUMN_05 VARCHAR,
    SOURCE_COLUMN_06 VARCHAR,
    SOURCE_COLUMN_07 VARCHAR,
    SOURCE_COLUMN_08 VARCHAR,
    SOURCE_COLUMN_09 VARCHAR,
    SOURCE_COLUMN_10 VARCHAR,
    SOURCE_COLUMN_11 VARCHAR,
    SOURCE_COLUMN_12 VARCHAR,
    SOURCE_FILENAME VARCHAR,
    SOURCE_ROW_NUMBER NUMBER(38, 0),
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ
)
COMMENT = 'Unmodified 12-position member feed rows and Snowpipe metadata';

DEFINE TABLE SKYPOINTS_DB.RAW.REDEMPTION_RAW
(
    PAYLOAD VARIANT,
    SOURCE_FILENAME VARCHAR,
    SOURCE_ROW_NUMBER NUMBER(38, 0),
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ
)
COMMENT = 'Unmodified partner redemption JSON documents and Snowpipe metadata';

DEFINE STAGE SKYPOINTS_DB.RAW.MEMBER_PROFILE_S3_STAGE
    URL = 's3://<AWS_S3_BUCKET>/<AWS_S3_MEMBERS_PREFIX>'
    STORAGE_INTEGRATION = SKYPOINTS_S3_STORAGE_INT
    FILE_FORMAT = (FORMAT_NAME = SKYPOINTS_DB.RAW.MEMBER_PROFILE_CSV)
    COMMENT = 'Member profile S3 landing prefix';

DEFINE STAGE SKYPOINTS_DB.RAW.REDEMPTION_S3_STAGE
    URL = 's3://<AWS_S3_BUCKET>/<AWS_S3_REDEMPTIONS_PREFIX>'
    STORAGE_INTEGRATION = SKYPOINTS_S3_STORAGE_INT
    FILE_FORMAT = (FORMAT_NAME = SKYPOINTS_DB.RAW.REDEMPTION_JSON)
    COMMENT = 'Redemption JSON S3 landing prefix';

DEFINE PIPE SKYPOINTS_DB.RAW.MEMBER_PROFILE_PIPE
    AUTO_INGEST = TRUE
    COMMENT = 'Auto-ingest pipe-delimited member profile files'
AS
COPY INTO SKYPOINTS_DB.RAW.MEMBER_PROFILE_RAW
FROM
(
    SELECT
        $1::VARCHAR,
        $2::VARCHAR,
        $3::VARCHAR,
        $4::VARCHAR,
        $5::VARCHAR,
        $6::VARCHAR,
        $7::VARCHAR,
        $8::VARCHAR,
        $9::VARCHAR,
        $10::VARCHAR,
        $11::VARCHAR,
        $12::VARCHAR,
        METADATA$FILENAME::VARCHAR,
        METADATA$FILE_ROW_NUMBER::NUMBER(38, 0),
        METADATA$FILE_CONTENT_KEY::VARCHAR,
        METADATA$START_SCAN_TIME::TIMESTAMP_LTZ
    FROM @SKYPOINTS_DB.RAW.MEMBER_PROFILE_S3_STAGE
)
FILE_FORMAT = (FORMAT_NAME = SKYPOINTS_DB.RAW.MEMBER_PROFILE_CSV)
ON_ERROR = SKIP_FILE;

DEFINE PIPE SKYPOINTS_DB.RAW.REDEMPTION_PIPE
    AUTO_INGEST = TRUE
    COMMENT = 'Auto-ingest partner redemption JSON files'
AS
COPY INTO SKYPOINTS_DB.RAW.REDEMPTION_RAW
FROM
(
    SELECT
        $1::VARIANT,
        METADATA$FILENAME::VARCHAR,
        METADATA$FILE_ROW_NUMBER::NUMBER(38, 0),
        METADATA$FILE_CONTENT_KEY::VARCHAR,
        METADATA$START_SCAN_TIME::TIMESTAMP_LTZ
    FROM @SKYPOINTS_DB.RAW.REDEMPTION_S3_STAGE
)
FILE_FORMAT = (FORMAT_NAME = SKYPOINTS_DB.RAW.REDEMPTION_JSON)
ON_ERROR = SKIP_FILE;
